export const SelectItem = forwardRef<
  ElementRef<typeof SelectPrimitive.Item>,
  ComponentPropsWithoutRef<typeof SelectPrimitive.Item>
>(({ className, children, value, ...props }, ref) => {
  // Radix Select reserves value="" for "clear selection / placeholder" — passing
  // an empty string here throws a runtime error that takes down the whole page.
  // Coerce to a non-empty sentinel with a dev warning so callers can fix it.
  const safeValue = value === '' || value == null
    ? (process.env.NODE_ENV !== 'production'
        ? console.warn('[SelectItem] value="" is reserved by Radix. Use a non-empty sentinel like "all".')
        : null) || '__empty__'
    : value;
  return (
    <SelectPrimitive.Item
      ref={ref}
      value={safeValue}
      className={cn(
        'relative flex w-full cursor-pointer select-none items-center rounded-sm py-1.5 pl-8 pr-2 text-sm outline-none',
        'focus:bg-accent focus:text-accent-foreground data-[disabled]:pointer-events-none data-[disabled]:opacity-50',
        className,
      )}
      {...props}
    >
      <span className="absolute left-2 flex h-3.5 w-3.5 items-center justify-center">
        <SelectPrimitive.ItemIndicator>
          <Check className="h-4 w-4" />
        </SelectPrimitive.ItemIndicator>
      </span>
      <SelectPrimitive.ItemText>{children}</SelectPrimitive.ItemText>
    </SelectPrimitive.Item>
  );
});
SelectItem.displayName = SelectPrimitive.Item.displayName;

